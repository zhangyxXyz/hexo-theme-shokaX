export function solarTermDate(year: number, term: string): { month: number; day: number } | undefined {
  if (!Number.isInteger(year) || year < solarTermStartYear || year > solarTermEndYear) return
  const index = solarTerms.indexOf(term as SolarTerm)
  if (index === -1) return
  return {
    month: Math.floor(index / 2) + 1,
    day: Number(daysByYear[year - solarTermStartYear].slice(index * 2, index * 2 + 2))
  }
}
